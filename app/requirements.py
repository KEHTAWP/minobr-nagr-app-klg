#: Награды, для которых требование к стажу в сфере повышается, если у
#: кандидата нет ни одной ведомственной награды Министерства просвещения.
#: Это условие нельзя проверить автоматически — наличие наград человек
#: указывает свободным текстом, — поэтому оно выводится подсказкой.
WITHOUT_DEPARTMENTAL_AWARD = {
    "minpros7": 40,      # Нагрудный знак «Почетный наставник»
    "minpros8": 40,      # Нагрудный знак «За верность профессии»
    "minpros4": 20,      # Почетный работник сферы образования
    "minpros5": 20,      # Почетный работник сферы воспитания детей и молодежи
}


def sphere_note(award_id: str) -> str:
    """Подсказка к стажу в сфере, если требование зависит от прежних наград."""
    years = WITHOUT_DEPARTMENTAL_AWARD.get(award_id)
    if not years:
        return ""
    return (
        "Если у кандидата нет ни одной ведомственной награды Министерства "
        f"просвещения Российской Федерации, стаж работы в сфере образования "
        f"должен быть не менее {years} лет."
    )


def for_award(award_id: str) -> Optional[dict]:
    """Требования к стажу для награды или None, если их нет."""
    return MIN_STAZH.get(award_id)


def rules_for(award_id: str) -> Dict[str, dict]:
    """
    Правила проверки в виде {поле анкеты: {min, label, quote}}.

    Используется анкетой, чтобы не дать указать стаж меньше требуемого.
    """
    data = MIN_STAZH.get(award_id)
    if not data:
        return {}
    out = {}
    for kind, field in FIELD_BY_KIND.items():
        if kind in data:
            out[field] = {
                "min": data[kind],
                "label": LABEL_BY_KIND[kind],
                "quote": data.get("quote", ""),
            }
    return out
