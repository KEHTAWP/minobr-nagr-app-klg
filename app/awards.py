def documents_for(award_id: str, level: int) -> List[str]:
    """Возвращает список бланков для награды в порядке их следования в PDF."""
    if level == 1:
        return [DOC_KADROVAYA, DOC_HARAKTERISTIKA]

    if level == 2:
        if award_id in GOVERNOR_AWARDS:
            return [DOC_KADROVAYA, DOC_HARAKTERISTIKA, DOC_SOGLASIE_KO]
        return [DOC_KADROVAYA, DOC_NAGRLIST_KO, DOC_SOGLASIE_KO]

    if level == 3:
        if award_id == OTLICHNIK:
            return [DOC_KADROVAYA, DOC_PREDSTAVLENIE, DOC_SOGLASIE_MP]
        return [DOC_KADROVAYA, DOC_NAGRLIST_MP]

    if level == 4:
        return [DOC_KADROVAYA, DOC_HARAKTERISTIKA]

    raise ValueError(f"Неизвестный уровень награды: {level}")


