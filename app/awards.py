def completion_message(level: int, award_id: str = "",
                       org_genitive: str = "") -> str:
    """
    Текст окна, показываемого после формирования пакета документов.

    Для «Отличника просвещения» в перечень подставляется название
    организации в родительном падеже — его берут из анкеты, где
    пользователь может указать падеж сам.
    """
    if award_id == OTLICHNIK:
        from .textutil import lower_first
        org = (org_genitive or "").strip()
        org = lower_first(org) if org else "вашей организации"
        extra = _EXTRA_OTLICHNIK.format(org=org)
    else:
        extra = _EXTRA[level]

    return (
        "Спасибо за использование нашего сервиса! Не забудьте проставить все "
        "необходимые подписи, а также " + extra + "\n\n" + _CONTACTS
    )


# --- загрузка справочника наград ------------------------------------------

_registry: Dict[str, dict] = {}
_levels: List[dict] = []


def _load() -> None:
    global _registry, _levels
    if _registry:
        return
    with open(_DATA, encoding="utf-8") as fh:
        data = json.load(fh)
    _levels = data["levels"]
    for lvl in _levels:
        for award in lvl["awards"]:
            # дополняем сам объект из справочника, а не копию: главному
            # экрану нужны те же сведения, что и карточке награды
            award["level"] = lvl["level"]
            award["levelTitle"] = lvl["title"]
            award["documents"] = documents_for(award["id"], lvl["level"])
            award["period"] = periods.text_for(award["id"])
            _registry[award["id"]] = award


def all_levels() -> List[dict]:
    """Структура «уровни → награды» для главного экрана."""
    _load()
    return _levels


def get_award(award_id: str) -> dict:
    """Карточка награды по её идентификатору."""
    _load()
    if award_id not in _registry:
        raise KeyError(f"Награда не найдена: {award_id}")
    return _registry[award_id]
